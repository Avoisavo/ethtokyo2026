#!/usr/bin/env node
// Generates app/ens/_lib/ens/abis/*.ts and app/ens/_lib/ens/deployments.ts from the ENSv2
// Sepolia deployment artifacts in ensdomains/contracts-v2.
//
// Pinned to the same contracts-v2 commit the ENS docs use for their
// Deployments table, so addresses and ABIs always describe one deployment set.
// To pick up a new deployment, bump CONTRACTS_V2_COMMIT and re-run:
//
//   npm run gen:ens-abis
//
// Set ENSV2_ARTIFACTS_DIR to a local checkout's contracts/deployments/sepolia
// directory to skip the network fetch.

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { getAddress } from "viem";

const CONTRACTS_V2_COMMIT = "71a3b7339dbc55ab47667abdfe8303bac4f4c24e";
const RAW = `https://raw.githubusercontent.com/ensdomains/contracts-v2/${CONTRACTS_V2_COMMIT}/contracts`;
const ADDRESSES_MD = `${RAW}/docs/addresses/sepolia.md`;
const ARTIFACTS = `${RAW}/deployments/sepolia`;

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const abisDir = path.join(root, "app/ens/_lib/ens/abis");
const localDir = process.env.ENSV2_ARTIFACTS_DIR;

async function readText(url, localPath) {
  if (localDir && localPath) return fs.readFile(localPath, "utf8");
  const res = await fetch(url);
  if (!res.ok) throw new Error(`fetch ${url} failed (${res.status})`);
  return res.text();
}

function parseAddressesMd(source) {
  const rows = new Map();
  const entry = /^\|\s*([A-Za-z0-9]+)\s*\|\s*\[(0x[0-9a-fA-F]{40})\]/gm;
  for (const m of source.matchAll(entry)) rows.set(m[1], m[2]);
  if (rows.size === 0) throw new Error("no address rows parsed from sepolia.md");
  const deployedAt = source.match(/\*\*Deployed at:\*\*\s*(\S+)/)?.[1];
  return { rows, deployedAt };
}

const md = await readText(
  ADDRESSES_MD,
  localDir && path.join(localDir, "../../docs/addresses/sepolia.md"),
);
const { rows, deployedAt } = parseAddressesMd(md);

await fs.rm(abisDir, { recursive: true, force: true });
await fs.mkdir(abisDir, { recursive: true });

const header = `// Generated by scripts/gen-ens-abis.mjs from ensdomains/contracts-v2@${CONTRACTS_V2_COMMIT.slice(0, 7)}. Do not edit.\n`;
const entries = [];

for (const [name, mdAddress] of [...rows.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  const artifact = JSON.parse(
    await readText(`${ARTIFACTS}/${name}.json`, localDir && path.join(localDir, `${name}.json`)),
  );
  if (artifact.address.toLowerCase() !== mdAddress.toLowerCase())
    throw new Error(`address mismatch for ${name}: ${mdAddress} vs ${artifact.address}`);

  await fs.writeFile(
    path.join(abisDir, `${name}.ts`),
    `${header}\nexport const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  entries.push({
    name,
    abi: artifact.abi,
    address: getAddress(mdAddress),
    contractName: artifact.contractName,
    sourceName: artifact.sourceName,
    deployBlock: artifact.receipt?.blockNumber ? BigInt(artifact.receipt.blockNumber) : undefined,
  });
}

await fs.writeFile(
  path.join(abisDir, "index.ts"),
  header + "\n" + entries.map((e) => `export { ${e.name}Abi } from "./${e.name}";`).join("\n") + "\n",
);

// Deduplicated error and event fragments across every contract, so a revert
// or receipt log from any ENSv2 contract (or proxy of one) can be decoded
// without knowing which contract produced it.
const signature = (f) =>
  `${f.name}(${f.inputs.map((i) => `${i.type}${i.indexed ? " indexed" : ""}`).join(",")})`;
const fragments = { error: new Map(), event: new Map() };
for (const e of entries)
  for (const f of e.abi) if (Object.hasOwn(fragments, f.type)) fragments[f.type].set(signature(f), f);
for (const [type, file, ident] of [
  ["error", "errors.ts", "ensErrorsAbi"],
  ["event", "events.ts", "ensEventsAbi"],
]) {
  const list = [...fragments[type].entries()].sort(([a], [b]) => a.localeCompare(b)).map(([, f]) => f);
  await fs.writeFile(
    path.join(abisDir, file),
    `${header}\nexport const ${ident} = ${JSON.stringify(list, null, 2)} as const;\n`,
  );
}

const body = entries
  .map(
    (e) =>
      `  ${e.name}: {\n` +
      `    address: "${e.address}",\n` +
      `    contractName: "${e.contractName}",\n` +
      `    sourceName: "${e.sourceName}",\n` +
      `    deployBlock: ${e.deployBlock === undefined ? "undefined" : `${e.deployBlock}n`},\n` +
      `  },`,
  )
  .join("\n");

await fs.writeFile(
  path.join(root, "app/ens/_lib/ens/deployments.ts"),
  `${header}
export const CONTRACTS_V2_COMMIT = "${CONTRACTS_V2_COMMIT}";
export const DEPLOYED_AT = "${deployedAt ?? ""}";

export const ENSV2_SEPOLIA = {
${body}
} as const;

export type ENSv2ContractName = keyof typeof ENSV2_SEPOLIA;
`,
);

console.log(`Wrote ${entries.length} ABIs to app/ens/_lib/ens/abis and app/ens/_lib/ens/deployments.ts`);
